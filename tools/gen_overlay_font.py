#!/usr/bin/env python3
"""Generates platform/overlay_font.h: anti-aliased ASCII (32..126) glyph bitmaps of DejaVu Sans Mono for the
in-game overlay. Run once; the output is committed so building needs neither PIL nor the font."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZES = [14, 20, 28]

out = ["/* Generated by tools/gen_overlay_font.py from DejaVu Sans Mono (Bitstream Vera licence). */",
       "#ifndef BEER_OVERLAY_FONT_H", "#define BEER_OVERLAY_FONT_H", "#include <stdint.h>", ""]
meta = []
for index, size in enumerate(SIZES):
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    cell_w = int(round(font.getlength("M")))
    cell_h = ascent + descent
    data = []
    for code in range(32, 127):
        img = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(img).text((0, 0), chr(code), font=font, fill=255)
        data.extend(img.tobytes())
    out.append("static const uint8_t overlay_font_%d[%d] = {" % (index, len(data)))
    for i in range(0, len(data), 32):
        out.append("    " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    out.append("};")
    meta.append((cell_w, cell_h))
out.append("")
out.append("typedef struct { int cell_w, cell_h; const uint8_t *glyphs; } OverlayFont;")
out.append("static const OverlayFont overlay_fonts[%d] = {" % len(SIZES))
for index, (w, h) in enumerate(meta):
    out.append("    { %d, %d, overlay_font_%d }," % (w, h, index))
out.append("};")
out.append("#define OVERLAY_FONT_COUNT %d" % len(SIZES))
out.append("#endif")
open("platform/overlay_font.h", "w").write("\n".join(out) + "\n")
print(meta)
