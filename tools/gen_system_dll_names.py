#!/usr/bin/env python3
"""Generates platform/win32_system_dll_names.h: the base names of the DLLs a Windows installation provides, taken
from Wine's PE DLL directory (the same reference tools/gen_module_exports.py uses). LoadLibrary falls back to an
inert compatibility module only for these names; any other DLL that is not on disk fails with ERROR_MOD_NOT_FOUND,
as on Windows."""
import os, sys
DLL_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/lib/x86_64-linux-gnu/wine/x86_64-windows"
names = sorted({f.lower() for f in os.listdir(DLL_DIR) if f.lower().endswith((".dll", ".drv", ".ocx", ".sys", ".cpl"))})
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "platform", "win32_system_dll_names.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_system_dll_names.py from Wine's PE DLL directory. Do not edit. */\n")
    f.write("static const char *const g_windows_system_dll_names[] = {\n")
    for n in names: f.write('    "%s",\n' % n)
    f.write("};\n")
print(len(names), "names")
