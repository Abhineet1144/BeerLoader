#!/usr/bin/env python3
"""Compiles a GLSL compute shader with glslc and writes it as a C array: gen_spv_header.py in.comp out.h name"""
import struct, subprocess, sys
src, out, name = sys.argv[1:4]
spv = subprocess.run(["glslc", "-O", "--target-env=vulkan1.1", "-fshader-stage=compute", src, "-o", "-"], check=True, capture_output=True).stdout
words = struct.unpack("<%dI" % (len(spv) // 4), spv)
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_spv_header.py from %s */\nstatic const uint32_t %s[] = {\n" % (src, name))
    for i in range(0, len(words), 8):
        f.write("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
    f.write("};\n")
print(name, len(words), "words")
