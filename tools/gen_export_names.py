#!/usr/bin/env python3
"""Emit a C include listing the export names of PE DLLs (used to recognise real system exports)."""
import struct, sys

def exports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    nsec, = struct.unpack_from('<H', d, pe + 6)
    optsz, = struct.unpack_from('<H', d, pe + 20)
    opt = pe + 24
    magic, = struct.unpack_from('<H', d, opt)
    ddir = opt + (112 if magic == 0x20b else 96)
    rva, size = struct.unpack_from('<II', d, ddir)
    secs = []
    so = opt + optsz
    for i in range(nsec):
        vsz, va, rsz, raw = struct.unpack_from('<IIII', d, so + 40 * i + 8)
        secs.append((va, max(vsz, rsz), raw))
    def off(r):
        for va, sz, raw in secs:
            if va <= r < va + sz:
                return r - va + raw
        raise ValueError(hex(r))
    e = off(rva)
    nnames, = struct.unpack_from('<I', d, e + 24)
    names_rva, = struct.unpack_from('<I', d, e + 32)
    out = []
    for i in range(nnames):
        n, = struct.unpack_from('<I', d, off(names_rva) + 4 * i)
        o = off(n)
        out.append(d[o:d.index(b'\0', o)].decode())
    return out

symbol, *paths = sys.argv[1:]
names = sorted({n for p in paths for n in exports(p)})
print('/* Generated by tools/gen_export_names.py from: %s */' % ', '.join(p.split('/')[-1] for p in paths))
print('static const char *const %s[] = {' % symbol)
for n in names:
    print('    "%s",' % n)
print('};')
